export function hasOrdinaryTypeDamage(move) {
  const normalized = String(move.name || "")
    .toLowerCase()
    .replace(/[^a-z]/g, "");
  return Boolean(
    move.type &&
      ["physical", "special"].includes(move.category) &&
      move.power !== 0 &&
      !SPECIAL_DAMAGE_MOVES.has(normalized),
  );
}
